"            return '<a href=\"' + u + '\" download=\"' + seg + '\" class=\"inline-flex items-center gap-2 px-3.5 py-2 bg-indigo-50 dark:bg-indigo-900/30 border border-indigo-100 dark:border-indigo-800/60 text-indigo-600 dark:text-indigo-300 text-xs font-extrabold rounded-xl hover:bg-indigo-100 dark:hover:bg-indigo-900/50 transition-colors\">' + mvAdjIcono(a.t) + 'Descargar ' + aaEsc(a.n) + ' (' + mvAdjFmtSize(a.s) + ')</a>';",
"        }",
