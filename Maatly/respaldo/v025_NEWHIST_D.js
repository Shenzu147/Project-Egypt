"        /* ---------- v0.25: Visor de adjuntos (z-140; revoca objectURL al cerrar) ---------- */",
"        let mvAdjUrls = [];",
"",
"        function mvAdjMimeDe(a) {",
"            const nm = String(a.n || '').toLowerCase();",
"            if (a.t === 'pdf' || nm.indexOf('.pdf') !== -1) return 'application/pdf';",
"            if (nm.indexOf('.png') !== -1) return 'image/png';",
"            if (nm.indexOf('.webp') !== -1) return 'image/webp';",
"            if (nm.indexOf('.svg') !== -1) return 'image/svg+xml';",
"            return 'image/jpeg';",
"        }",
"",
"        function mvAdjBlobUrl(a, mime) {",
"            try {",
"                const b64 = String(a.d || '').split(',')[1] || '';",
"                const bin = atob(b64);",
"                const u8 = new Uint8Array(bin.length);",
"                for (let i = 0; i < bin.length; i++) u8[i] = bin.charCodeAt(i);",
"                const url = URL.createObjectURL(new Blob([u8], { type: mime || mvAdjMimeDe(a) }));",
"                mvAdjUrls.push(url);",
"                return url;",
"            } catch (e) { return ''; }",
"        }",
"",
"        function mvAdjVistaArchivo(a) {",
"            if (a.t === 'img') return '<img src=\"' + a.d + '\" alt=\"' + aaEsc(a.n) + '\" class=\"w-full rounded-xl border border-slate-200 dark:border-slate-700\" style=\"max-height:55vh\" />';",
"            if (a.t === 'pdf') {",
"                const u = mvAdjBlobUrl(a, 'application/pdf');",
